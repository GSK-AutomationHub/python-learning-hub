# while loop can be used when we are uncertain about no of iterations
# loop steps --> initialization, condition check, increment / decrement

i = 1  # Initialization

while i <= 30:  # Condition Check
    print(i, end=" ")
    i += 1  # increment

print("\n")

j = 30  # Initialization

while j >= 0:  # Condition Check
    print(j, end=" ")
    j -= 1  # # Condition Check
