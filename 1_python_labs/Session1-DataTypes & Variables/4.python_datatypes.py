'''
Python Data Types
Text type : str , Number Type : int, float , Sequence type  : list, tuple
Mapping type : dict , Set type : set , Boolean type : bool
'''

firstname = 'Ganesh'
cricket_score = 150
pi = 3.14
fruits = ['mango', 'apple', 'banana']
testcase = ('TC Number', 'priority', 'title', 'steps', 'expected result', 'actual result')
student_record = {'name': 'Ram', 'school': 'Krishan Public Highschool', 'Std': '7th', 'roll no': '007'}
bundle_set = {'mobile phone','charger','headset','screen guard','warranty card'}
is_json = True

# type() function prints data type of variable
print(type(firstname),firstname)
print(type(cricket_score),cricket_score)
print(type(pi),pi)
print(type(fruits),fruits)
print(type(testcase),testcase)
print(type(student_record),student_record)
print(type(bundle_set),bundle_set)
print(type(is_json),is_json)