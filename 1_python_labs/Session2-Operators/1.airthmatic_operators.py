x, y = 2, 5

print(x + y)  # addition operator
print(y - x)  # subtraction operator
print(x * y)  # multiplication operator
print(y / x)  # division operator

print(y // x)  # floor division operator returns quotient only
print(y % x)   # mod operator returns reminder

print(y ** x)  # exponential operator returns pow
print(y.__pow__(x))
