# relational operators also called as comparison operators
#  ==, > , < , >= , <= , !=
# they always returns boolean value

x, y = 2, 5

print(x == y)  # equal to comparison
print(x > y)   # greater than comparison
print(x < y)   # less than comparison
print(x >= y)  # greater than equal to comparison
print(x <= y)  # less than equal to comparison
print(x != y)  # not equal to comparison
