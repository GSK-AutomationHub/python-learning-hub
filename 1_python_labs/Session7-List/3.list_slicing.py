print("------------- slicing the list list[ST:EI] -------------")

mylist = ['mango', 'apple', 'banana', 'gauva', 'cherry', 'kiwi', 'pomegranate']
print("mylist5[2:5] slice the with SI 2 & EI (n-1) i.e. 4 here -")
print(mylist[2:5])
print("mylist5[:6] slice the with SI as 0 as no SI mentioned & EI (n-1) i.e. 5 here -")
print(mylist[:6])
print("mylist5[3:] slice the with SI as 3 till end index as no EI mentioned here -")
print(mylist[3:])
print("mylist5[-1] gives item at last index in list -")
print(mylist[-1])
print("mylist5[-5:-1] slice list with SI as last 5th till last index-1")
print(mylist[-5:-1])